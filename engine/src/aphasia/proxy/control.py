"""`aphasia proxy start|status|stop` — run the LiteLLM gateway in its own env via uvx, with the
recorder loaded. Reads `[upstream]`/`[proxy]` and the role secrets from aphasia.config. The attacker
LLM and generic OPENAI_*/ANTHROPIC_* vars never reach the proxy process (clean env, built from scratch).
"""
import os
import secrets as pysecrets
import shutil
import signal
import subprocess
import time
from importlib import resources
from pathlib import Path

import httpx

from aphasia import config as cfg

RECORDER_CALLBACK = "aphasia_recorder.recorder"


def _write_config(d: Path, c: cfg.Config) -> Path:
    """Generate config.yaml from the stored [upstream]/[proxy] settings. Secrets are env refs only."""
    lp = [f'      model: {c.upstream.model}']
    if c.upstream.api_base:
        lp.append(f'      api_base: {c.upstream.api_base}')
    lp.append('      api_key: os.environ/APHASIA_UPSTREAM_API_KEY')
    body = (
        "# Generated by `aphasia proxy start`. Secrets are env references only — never written here.\n"
        "model_list:\n"
        f"  - model_name: {c.proxy.alias}\n"
        "    litellm_params:\n" + "\n".join(lp) + "\n\n"
        "litellm_settings:\n"
        f"  callbacks: {RECORDER_CALLBACK}\n"
        "  drop_params: true\n\n"
        "general_settings:\n"
        "  master_key: os.environ/APHASIA_PROXY_KEY\n")
    p = d / "config.yaml"
    p.write_text(body)
    return p


def _copy_recorder(d: Path) -> None:
    src = resources.files("aphasia.proxy").joinpath("recorder.py").read_text()
    (d / "aphasia_recorder.py").write_text(src)


def _clean_env(d: Path, proxy_key: str, upstream_key: str, full: bool) -> dict:
    """Env built from scratch: no attacker key, no generic provider vars leak into the proxy."""
    env = {"PATH": os.environ.get("PATH", "/usr/bin:/bin"),
           "HOME": os.environ.get("HOME", str(Path.home())),
           "APHASIA_PROXY_KEY": proxy_key,
           "APHASIA_UPSTREAM_API_KEY": upstream_key,
           "APHASIA_PROXY_LOG": str(d / "proxy.jsonl"),
           "APHASIA_RUN_CONTEXT": str(d / "context.json")}
    if full:
        env["APHASIA_PROXY_FULL"] = "1"
    for k in ("HTTPS_PROXY", "HTTP_PROXY", "NO_PROXY", "SSL_CERT_FILE", "REQUESTS_CA_BUNDLE",
              "OLLAMA_HOST"):
        if os.environ.get(k):
            env[k] = os.environ[k]
    return env


def _uvx_cmd(config_path: Path, host: str, port: str) -> list[str]:
    return ["uvx", "--from", "litellm[proxy]==1.111.0", "litellm",
            "--config", str(config_path), "--host", host, "--port", port]


def _ensure_proxy_key(c: cfg.Config) -> str:
    key = c.secret(cfg.PROXY_KEY)
    if key:
        return key
    key = "sk-aphasia-" + pysecrets.token_urlsafe(18)
    c.secrets[cfg.PROXY_KEY] = key
    cfg.save(c)  # persist to secrets.env
    return key


def _health_ok(base: str, timeout: float = 1.5) -> bool:
    try:
        return httpx.get(base.rstrip("/") + "/health/liveliness", timeout=timeout).status_code == 200
    except httpx.HTTPError:
        return False


def start(c: cfg.Config, *, provider_model: str = "", api_base: str = "", alias: str = "",
          listen: str = "", full: bool = False, wait_s: int = 90,
          spawn=subprocess.Popen) -> dict:
    """Write config + recorder, generate/keep the proxy key, spawn the gateway, wait for health.
    Returns the agent-facing settings. `spawn` is injectable for tests."""
    if provider_model:
        c.upstream.model = provider_model
    if api_base:
        c.upstream.api_base = api_base
    if alias:
        c.proxy.alias = alias
    if listen:
        c.proxy.listen = listen
    if full:
        c.proxy.full_text = True
    if not c.upstream.model:
        raise ValueError("no upstream model; pass --provider-model or set [upstream].model (aphasia setup)")
    host = c.proxy.listen.split(":")[0]
    port = c.proxy.listen.split(":")[1] if ":" in c.proxy.listen else "4000"
    if host not in ("127.0.0.1", "localhost") and not listen:
        raise ValueError("refusing a non-local bind without an explicit --listen (prompts flow through it)")
    if not shutil.which("uvx"):
        raise ValueError("uvx not found; install uv (https://docs.astral.sh/uv/) to run the proxy")

    d = Path(c.proxy.dir)
    d.mkdir(parents=True, exist_ok=True)
    proxy_key = _ensure_proxy_key(c)
    upstream_key = c.secret(cfg.UPSTREAM_KEY) or "dummy"  # local models need no real key
    cfg_path = _write_config(d, c)
    _copy_recorder(d)
    env = _clean_env(d, proxy_key, upstream_key, c.proxy.full_text)

    logf = (d / "proxy.out").open("w")
    proc = spawn(_uvx_cmd(cfg_path, host, port), env=env, stdout=logf, stderr=subprocess.STDOUT)
    (d / "proxy.pid").write_text(str(proc.pid))

    base = c.proxy.url
    for _ in range(wait_s):
        if proc.poll() is not None:
            raise RuntimeError(f"proxy exited early (rc={proc.returncode}); see {d / 'proxy.out'}")
        if _health_ok(base):
            break
        time.sleep(1)
    else:
        raise RuntimeError(f"proxy did not become healthy in {wait_s}s; see {d / 'proxy.out'}")

    return {"base_url": f"{base}/v1", "anthropic_base": base, "api_key": proxy_key,
            "model": c.proxy.alias, "pid": proc.pid, "dir": str(d)}


def status(c: cfg.Config) -> dict:
    d = Path(c.proxy.dir)
    pidf = d / "proxy.pid"
    if not pidf.exists():
        return {"running": False, "reason": "no pid file"}
    pid = int(pidf.read_text().strip() or "0")
    alive = _pid_alive(pid)
    return {"running": alive and _health_ok(c.proxy.url), "pid": pid, "alive": alive,
            "healthy": _health_ok(c.proxy.url), "dir": str(d)}


def stop(c: cfg.Config) -> dict:
    d = Path(c.proxy.dir)
    pidf = d / "proxy.pid"
    if not pidf.exists():
        return {"stopped": False, "reason": "no pid file"}
    pid = int(pidf.read_text().strip() or "0")
    if pid and _pid_alive(pid):
        try:
            os.kill(pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
        for _ in range(10):
            if not _pid_alive(pid):
                break
            time.sleep(0.3)
        if _pid_alive(pid):
            try:
                os.kill(pid, signal.SIGKILL)
            except ProcessLookupError:
                pass
    pidf.unlink(missing_ok=True)
    return {"stopped": True, "pid": pid}


def _pid_alive(pid: int) -> bool:
    if pid <= 0:
        return False
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    return True
